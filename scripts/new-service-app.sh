#!/usr/bin/env bash
# Generates apps/app-<module>-service from one template, so the eight service apps stay uniform.
#
#   scripts/new-service-app.sh <module>    generate one
#   scripts/new-service-app.sh --all       generate all eight
#   scripts/new-service-app.sh --check     fail if a generated app differs from what the template would produce now
#
# A service app contains its own -impl plus exactly the -api artifacts the module may call. That set is read from the
# module's package-info.java (@ApplicationModule(allowedDependencies = ...)), the single source of truth, and enforced by
# the maven-enforcer rule that is generated into the app's pom.
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
modules=(catalog customers pricing inventory payments shipping notifications orders)
declare -A port=([orders]=9181 [catalog]=9182 [pricing]=9183 [inventory]=9184 [customers]=9185 [payments]=9186 [shipping]=9187 [notifications]=9188)

allowed() { # the modules <m> may call, one per line
  grep -o '"[a-z]*::api"' "$root/modules/$1/$1-impl/src/main/java/com/acme/$1/package-info.java" | tr -d '"' | sed 's/::api//' | sort || true
}

generate() { # $1 module, $2 output directory
  local m="$1" out="$2" deps dep_poms="" dep_includes="" dep_yaml="" d
  mapfile -t deps < <(allowed "$m")
  for d in "${deps[@]}"; do
    [ -z "$d" ] && continue
    dep_poms+="    <dependency><groupId>com.acme.macro</groupId><artifactId>$d-api</artifactId></dependency>"$'\n'
    dep_includes+="                    <include>com.acme.macro:$d-api</include>"$'\n'
    dep_yaml+="  $d:"$'\n'"    enabled: false"$'\n'"    url: http://localhost:${port[$d]}/rpc/$d"$'\n'
  done
  mkdir -p "$out/src/main/java/com/acme" "$out/src/main/resources" "$out/src/test/java/com/acme"

  cat > "$out/pom.xml" <<POM
<?xml version="1.0" encoding="UTF-8"?>
<!-- GENERATED by scripts/new-service-app.sh. Edit the template there, not this file. -->
<project xmlns="http://maven.apache.org/POM/4.0.0" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
         xsi:schemaLocation="http://maven.apache.org/POM/4.0.0 https://maven.apache.org/xsd/maven-4.0.0.xsd">
  <modelVersion>4.0.0</modelVersion>
  <parent>
    <groupId>com.acme.macro</groupId>
    <artifactId>macro-parent</artifactId>
    <version>0.1.0-SNAPSHOT</version>
    <relativePath>../../pom.xml</relativePath>
  </parent>
  <artifactId>app-$m-service</artifactId>
  <name>app-$m-service</name>

  <dependencies>
    <dependency><groupId>com.acme.macro</groupId><artifactId>$m-impl</artifactId></dependency>
${dep_poms}    <dependency><groupId>com.acme.macro</groupId><artifactId>rpc-spring-boot-starter</artifactId></dependency>
    <dependency><groupId>com.acme.macro</groupId><artifactId>demo-support</artifactId></dependency>
    <dependency><groupId>org.springframework.boot</groupId><artifactId>spring-boot-starter</artifactId></dependency>
    <dependency><groupId>org.springframework.boot</groupId><artifactId>spring-boot-starter-test</artifactId><scope>test</scope></dependency>
    <dependency><groupId>org.springframework.modulith</groupId><artifactId>spring-modulith-core</artifactId><scope>test</scope></dependency>
    <dependency><groupId>com.acme.macro</groupId><artifactId>module-support</artifactId><type>test-jar</type><scope>test</scope></dependency>
    <dependency><groupId>com.tngtech.archunit</groupId><artifactId>archunit</artifactId><scope>test</scope></dependency>
    <dependency><groupId>org.testcontainers</groupId><artifactId>testcontainers-postgresql</artifactId><scope>test</scope></dependency>
  </dependencies>

  <build>
    <plugins>
      <plugin>
        <groupId>org.springframework.boot</groupId>
        <artifactId>spring-boot-maven-plugin</artifactId>
        <executions><execution><goals><goal>repackage</goal></goals></execution></executions>
      </plugin>
      <plugin>
        <groupId>org.apache.maven.plugins</groupId>
        <artifactId>maven-enforcer-plugin</artifactId>
        <executions>
          <execution>
            <id>enforce-service-rules</id>
            <phase>validate</phase>
            <goals><goal>enforce</goal></goals>
            <configuration>
              <rules>
                <bannedDependencies>
                  <searchTransitive>true</searchTransitive>
                  <excludes>
                    <exclude>com.acme.macro:*-impl</exclude>
                    <exclude>com.acme.macro:*-api</exclude>
                  </excludes>
                  <includes>
                    <include>com.acme.macro:$m-impl</include>
                    <include>com.acme.macro:$m-api</include>
${dep_includes}                    <include>com.acme.macro:rpc-api</include>
                  </includes>
                  <message>app-$m-service may contain only $m-impl and the -api artifacts of the modules $m is allowed to call (see package-info.java of $m-impl).</message>
                </bannedDependencies>
              </rules>
            </configuration>
          </execution>
        </executions>
      </plugin>
    </plugins>
  </build>
</project>
POM

  cat > "$out/src/main/java/com/acme/Application.java" <<'JAVA'
package com.acme;

import org.springframework.boot.SpringApplication;
import org.springframework.boot.autoconfigure.SpringBootApplication;

@SpringBootApplication(excludeName = {
        // each module defines its own DataSource, Flyway, EntityManagerFactory and transaction manager
        "org.springframework.boot.jdbc.autoconfigure.DataSourceAutoConfiguration",
        "org.springframework.boot.jdbc.autoconfigure.DataSourceTransactionManagerAutoConfiguration",
        "org.springframework.boot.hibernate.autoconfigure.HibernateJpaAutoConfiguration",
        "org.springframework.boot.data.jpa.autoconfigure.DataJpaRepositoriesAutoConfiguration",
        "org.springframework.boot.flyway.autoconfigure.FlywayAutoConfiguration"})
public class Application {

    public static void main(String[] args) {
        SpringApplication.run(Application.class, args);
    }
}
JAVA

  cat > "$out/src/main/resources/application.yml" <<YAML
# GENERATED by scripts/new-service-app.sh. Everything here can be overridden by environment variables
# (for example MODULES_$(echo "$m" | tr a-z A-Z)_DATASOURCE_URL) or a profile.
server:
  port: ${port[$m]}
rpc:
  server:
    enabled: true
spring:
  application:
    name: app-$m-service
  profiles:
    group:
      demo: dev
  threads:
    virtual:
      enabled: true
management:
  endpoints:
    web:
      exposure:
        include: health,metrics
  endpoint:
    health:
      group:
        readiness:
          include: readinessState,modules
  health:
    probes:
      enabled: true
modules:
  $m:
    enabled: true
    datasource:
      url: jdbc:postgresql://localhost:5432/macro
      username: ${m}_app
      password: ${m}_app
      migration-username: ${m}_migrator
      migration-password: ${m}_migrator
${dep_yaml}
YAML

  local expected="\"$m\""
  for d in "${deps[@]}"; do [ -n "$d" ] && expected+=", \"$d\""; done
  cat > "$out/src/test/java/com/acme/ApplicationTests.java" <<JAVA
package com.acme;

import static org.assertj.core.api.Assertions.assertThat;

import io.macroservice.platform.support.testing.SharedPostgres;
import java.util.stream.Stream;
import org.junit.jupiter.api.Test;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.modulith.core.ApplicationModules;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;

/** GENERATED by scripts/new-service-app.sh. */
@SpringBootTest(properties = "spring.main.web-application-type=none")
@ActiveProfiles("demo")
class ApplicationTests {

    @DynamicPropertySource
    static void database(DynamicPropertyRegistry registry) {
        SharedPostgres.register(registry, "$m");
    }

    @Test
    void contextLoads() {
    }

    @Test
    void containsExactlyThisModuleAndTheApisItMayCall() {
        ApplicationModules modules = ApplicationModules.of(Application.class);
        modules.verify();
        assertThat(modules.stream().map(m -> m.getIdentifier().toString()))
                .containsExactlyInAnyOrderElementsOf(Stream.of($expected).toList());
    }
}
JAVA
  cat > "$out/src/test/java/com/acme/ArchitectureTests.java" <<'JAVA'
package com.acme;

import io.macroservice.platform.support.arch.AbstractModuleArchitectureTests;

/** GENERATED by scripts/new-service-app.sh. */
class ArchitectureTests extends AbstractModuleArchitectureTests {
}
JAVA
}

case "${1:-}" in
  --all)
    for m in "${modules[@]}"; do rm -rf "$root/apps/app-$m-service"; generate "$m" "$root/apps/app-$m-service"; done ;;
  --check)
    tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT; status=0
    for m in "${modules[@]}"; do
      generate "$m" "$tmp/app-$m-service"
      if ! diff -r -q -x target "$tmp/app-$m-service" "$root/apps/app-$m-service" >/dev/null; then
        echo "app-$m-service is out of date; run scripts/new-service-app.sh $m"; status=1
      fi
    done
    [ $status -eq 0 ] && echo "service apps are up to date"
    exit $status ;;
  "") echo "usage: $0 <module> | --all | --check" >&2; exit 2 ;;
  *)  rm -rf "$root/apps/app-$1-service"; generate "$1" "$root/apps/app-$1-service" ;;
esac
